// 백업 안내 문구 — 데이터를 바꾼 직후 토스트에 한 줄 덧붙인다.
//
// 이 앱의 데이터는 전부 브라우저 localStorage에 있어서, 브라우저 데이터를 지우거나
// 다른 기기로 옮기면 그대로 사라진다. 그래서 추가/수정/삭제처럼 되돌리기 어려운
// 변경을 한 직후에 백업 경로를 알려 준다.
//
// 붙이는 기준: 저장소의 데이터가 실제로 바뀐 성공 토스트에만 붙인다.
// - 실패(err) 토스트, '변경할 내용이 없습니다' 류, 단순 조회 결과에는 붙이지 않는다.
// - 설정 페이지(pages/settings.vue)는 백업·복원 메뉴가 있는 페이지 자신이므로 제외한다.

/** 토스트 둘째 줄에 들어갈 안내 문구 */
export const BACKUP_HINT = '설정 > 백업·복원에서 전체 데이터를 백업할 수 있습니다'

/**
 * 토스트 본문에 백업 안내를 둘째 줄로 덧붙인다.
 * 토스트 렌더링 쪽에 `whitespace-pre-line`이 있어야 줄바꿈이 보인다.
 */
export function withBackupHint(text: string): string {
  return `${text}\n${BACKUP_HINT}`
}
